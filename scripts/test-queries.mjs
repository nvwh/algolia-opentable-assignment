// Repeatable relevance check: runs every query from docs/TEST-LOG.md against the live index
// and writes what came back to docs/test-results.md, to paste into the "Observed" column.
// It is a report, not a pass/fail test: always exits 0 once it has printed.
import { readFileSync, writeFileSync } from 'node:fs'
import { algoliasearch } from 'algoliasearch'

const { ALGOLIA_APP_ID } = process.env
// Search-only key is enough (and safer); the admin key is only a fallback.
const key = process.env.VITE_ALGOLIA_SEARCH_KEY || process.env.ALGOLIA_ADMIN_KEY
if (!ALGOLIA_APP_ID || !key) {
  // Name the variables only, never print their values.
  console.error('Missing ALGOLIA_APP_ID and/or a key: set VITE_ALGOLIA_SEARCH_KEY (or ALGOLIA_ADMIN_KEY) in .env.')
  process.exit(1)
}

const { index } = JSON.parse(readFileSync('search-config/contract.json', 'utf8'))
const client = algoliasearch(ALGOLIA_APP_ID, key)

// Known places a TEST-LOG row can mention; the first column of the table has no coordinates.
const PLACES = {
  'New York': '40.7580,-73.9855',
  Houston: '29.7604,-95.3698',
  Denver: '39.7392,-104.9903',
  Europe: '48.8566,2.3522', // Paris
}

// Parse the markdown table: a data row looks like "| 10 | `query` (note) | Category | ... |".
// Query = first backticked text, or empty when the cell says "(empty)". Every place named in the
// cell becomes its own run (row 20 -> New York then Denver); none named -> New York.
// A cell mentioning "sort" is run on the Top rated replica.
const rows = []
for (const line of readFileSync('docs/TEST-LOG.md', 'utf8').split('\n')) {
  const cells = line.split('|').map((c) => c.trim())
  if (!/^\d+$/.test(cells[1] ?? '')) continue
  const cell = cells[2]
  const query = cell.includes('(empty)') ? '' : (cell.match(/`([^`]*)`/)?.[1] ?? '')
  const places = Object.keys(PLACES).filter((p) => cell.includes(p))
  const sorted = /sort/i.test(cell)
  for (const place of places.length ? places : ['New York']) {
    rows.push({ n: cells[1], query, place, indexName: sorted ? 'restaurants_rating_desc' : index })
  }
}
if (!rows.length) {
  console.error('No query rows found in docs/TEST-LOG.md (expected a markdown table with a numeric "#" column).')
  process.exit(1)
}

const miles = (m) => (m / 1609.34).toFixed(1)

const lines = []
for (const r of rows) {
  const { nbHits, hits } = await client.searchSingleIndex({
    indexName: r.indexName,
    searchParams: {
      query: r.query,
      aroundLatLng: PLACES[r.place],
      aroundRadius: 'all', // never filter by distance, only rank by it
      aroundPrecision: [{ from: 0, value: 5000 }, { from: 80000, value: 1000000 }], // same bands as the app (app/src/location.js)
      getRankingInfo: true,
      hitsPerPage: 3,
    },
  })
  const top = hits.map((h) => {
    const ri = h._rankingInfo
    return `${h.name} (${h.city}) [typos:${ri?.nbTypos ?? '?'}, ${miles(ri?.matchedGeoLocation?.distance ?? 0)}mi]`
  })
  // Zero hits deserve a look, except for the nonsense query where zero is the expected answer.
  const flag = nbHits === 0 && r.query !== 'xqzv' ? ' check' : ''
  const sortNote = r.indexName === index ? '' : ' (Top rated)'
  lines.push([r.n, `${r.query || '(empty)'}${sortNote}`, r.place, `${nbHits}${flag}`, top.join('; ') || '-'])
}

const header = '# | query | location | nbHits | top 3'
console.log([header, ...lines.map((l) => l.join(' | '))].join('\n'))

const stamp = new Date().toISOString()
const md = [
  `# Test results (${stamp})`,
  '',
  'Generated by `scripts/test-queries.mjs`. Rows marked "check" returned 0 hits.',
  '',
  '| # | Query | Location | nbHits | Top 3 |',
  '|---|---|---|---|---|',
  ...lines.map((l) => `| ${l.join(' | ')} |`),
  '',
].join('\n')
writeFileSync('docs/test-results.md', md)
console.log('\nWritten to docs/test-results.md')
